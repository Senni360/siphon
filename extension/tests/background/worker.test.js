import test from 'node:test';
import assert from 'node:assert/strict';
import { setTimeout as wait } from 'node:timers/promises';
import { createChromeMock } from '../helpers/chrome-mock.js';
import { CMD } from '../../src/shared/protocol.js';

globalThis.chrome = createChromeMock();
const { background } = await import('../../src/background/service-worker.js');
await background.ready;

test('worker registers menus on startup and install opens setup', async () => {
  await wait(5);
  assert.equal(chrome.calls.menus.length, 8);
  assert.equal(chrome.calls.menus.find(item => item.id === 'siphon:download').contexts.length, 4);
  chrome.runtime.onInstalled.emit({ reason: 'install' }); await wait(5);
  assert.ok(chrome.calls.tabs.at(-1).url.endsWith('#setup'));
  assert.equal(chrome.calls.menus.length, 8);
});
test('async message router covers state/settings/probe/download/cancel/retry/history/native actions', async () => {
  const send = (cmd, args = {}) => chrome.runtime.sendMessage({ cmd, ...args });
  const state = await send(CMD.GET_STATE);
  assert.equal(state.host.state, 'ready'); assert.deepEqual(state.jobs, []); assert.ok(state.settings.format);
  assert.equal((await send(CMD.SET_SETTINGS, { patch: { format: 'flac', sendSiteCookies: false } })).format, 'flac');
  assert.equal((await send(CMD.GET_SETTINGS)).format, 'flac');
  assert.deepEqual(await send(CMD.PROBE, { url: 'https://a.test' }), {});
  assert.equal((await send(CMD.PROBE_TAB)).url, 'https://www.youtube.com/watch?v=abc');
  const { jobId } = await send(CMD.DOWNLOAD, { url: 'https://a.test/song', source: 'soundcloud' });
  assert.ok(jobId);
  const port = background.native.port;
  await send(CMD.SET_SETTINGS, { patch: { maxConcurrent: 16 } });
  await wait(0);
  assert.equal(chrome.calls.native.findLast(request => request.type === 'hello').maxConcurrent, 16);
  assert.equal(background.native.port, port, 'changing concurrency keeps running jobs on their port');
  const cancelled = await send(CMD.CANCEL, { jobId }); assert.ok(cancelled.cancelled);
  const retry = await send(CMD.RETRY, { jobId }); assert.ok(retry.jobId);
  await send(CMD.CANCEL, { jobId: retry.jobId });
  const tabJob = await send(CMD.DOWNLOAD_TAB, { options: { format: 'm4a' } });
  assert.equal(background.jobs.jobs.get(tabJob.jobId).options.format, 'm4a');
  await send(CMD.CANCEL, { jobId: tabJob.jobId });
  for (const cmd of [CMD.REVEAL, CMD.OPEN]) assert.deepEqual(await send(cmd, { path: 'C:\\Music\\song.flac' }), {});
  assert.deepEqual(await send(CMD.PICK_FOLDER), {}); assert.deepEqual(await send(CMD.UPDATE_HOST), {});
  assert.equal((await send(CMD.RECONNECT_HOST)).state, 'ready');
  assert.deepEqual((await send(CMD.CLEAR_HISTORY)).history, []);
  assert.equal((await send('unknown')).error.code, 'BAD_REQUEST');
  assert.equal((await send(CMD.DOWNLOAD, { url: 'chrome://settings' })).error.code, 'UNSUPPORTED_URL');
  assert.equal((await send(CMD.REVEAL)).error.code, 'BAD_REQUEST');
  background.native.disconnect();
});
test('context menu format, keyboard command, notifications, badge alarms and settings broadcasts', async () => {
  chrome.contextMenus.onClicked.emit({ menuItemId: 'siphon:format:opus', linkUrl: 'https://a.test/song', pageUrl: 'https://a.test' }, { title: 'Song' });
  await wait(10);
  const request = chrome.calls.native.findLast(message => message.type === 'download');
  assert.equal(request.url, 'https://a.test/song'); assert.equal(request.options.format, 'opus');
  await background.jobs.event({ jobId: request.jobId, state: 'done', title: 'Song', file: 'C:\\Music\\song.opus' });
  const notification = chrome.calls.notifications.at(-1);
  assert.equal(notification.title, 'Song'); assert.equal(notification.message, 'song.opus'); assert.equal(notification.buttons.length, 2);
  chrome.notifications.onClicked.emit(notification.id); await wait(5);
  assert.equal(chrome.calls.native.at(-1).type, 'reveal');
  chrome.notifications.onButtonClicked.emit(notification.id, 1); await wait(5);
  assert.equal(chrome.calls.native.at(-1).type, 'open');
  assert.equal(chrome.calls.badge.at(-1).text, '✓');
  chrome.alarms.onAlarm.emit({ name: 'siphon:badge' }); await wait(5);
  assert.equal(chrome.calls.badge.at(-1).text, '');
  chrome.commands.onCommand.emit('download-current'); await wait(10);
  assert.ok(background.jobs.list().length);
  assert.equal(chrome.calls.native.findLast(message => message.type === 'download').url, 'https://www.youtube.com/watch?v=abc');
  assert.ok(chrome.calls.broadcasts.some(message => message.evt === 'settings'));
  background.native.disconnect();
});
